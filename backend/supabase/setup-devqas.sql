CREATE VIEW public."fornecedor_stats" AS
SELECT f.id,
    f.full_name,
    f.nome_loja,
    count(DISTINCT v.id) AS total_vendas,
    count(DISTINCT av.id) AS total_avaliacoes,
    round(avg(av.nota), 2) AS nota_media,
    count(DISTINCT p.id) AS total_pecas_ativas,
    sum(v.preco_total) AS total_vendido
   FROM (((users f
     LEFT JOIN vendas v ON (((f.id = v.fornecedor_id) AND ((v.status)::text <> 'cancelada'::text))))
     LEFT JOIN avaliacoes_fornecedor av ON ((f.id = av.fornecedor_id)))
     LEFT JOIN pecas p ON (((f.id = p.fornecedor_id) AND ((p.status)::text = 'disponivel'::text))))
  WHERE ((f.tipo_usuario)::text = ANY ((ARRAY['fornecedor'::character varying, 'ambos'::character varying])::text[]))
  GROUP BY f.id, f.full_name, f.nome_loja;

