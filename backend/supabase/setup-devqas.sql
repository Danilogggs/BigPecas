   FROM (((vendas v
     JOIN pecas p ON ((v.peca_id = p.id)))
     JOIN users f ON ((v.fornecedor_id = f.id)))
     JOIN users c ON ((v.comprador_id = c.id)))
  WHERE ((v.status)::text = ANY ((ARRAY['pendente'::character varying, 'confirmada'::character varying])::text[]));

